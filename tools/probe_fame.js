const s = load();
console.log(`语料 ${s.lines} 句 / ${s.poems} 篇，加载 ${s.ms}ms\n`);
let bad = 0;
for (const q of LINES) {
  const r = judge(q);
  const tag = r.ok ? r.via.padEnd(8) : 'REJECT  ';
  if (!r.ok) bad++;
  const src = r.ok ? `《${r.source.title}》 ${r.source.author}·${r.source.dynasty}·${r.source.kind}` : r.reason;
  console.log(`${q.padEnd(12, '　')} ${tag} ${src}`);
}
console.log(`\n拒判 ${bad} / ${LINES.length}`);
